/**
 * Derives consistent dashboard metrics directly from the mock fixtures
 */
export function computeDashboardMetrics(
  seniors: SeniorProfile[],
  alerts: Alert[]
): DashboardMetrics {
  const byRisk: Record<string, number> = {
    LOW: 0,
    MODERATE: 0,
    HIGH: 0,
    URGENT_REVIEW: 0,
  };

  seniors.forEach((s) => {
    if (s.current_risk_level && byRisk[s.current_risk_level] !== undefined) {
      byRisk[s.current_risk_level]++;
    }
  });

  const activeAlerts = alerts.filter(
    (a) => a.status === "OPEN" || a.status === "ESCALATED"
  ).length;

  const ackAlerts = alerts.filter((a) => a.status === "ACKNOWLEDGED").length;
  const resAlerts = alerts.filter((a) => a.status === "RESOLVED").length;
  const escAlerts = alerts.filter((a) => a.status === "ESCALATED").length;

  // Defensible definition of overdue: seniors with no observation or missing last_observation_date
  const overdueCheckins = seniors.filter(
    (s) => !s.last_observation_date || s.current_risk_score === null
  ).length;

  return {
    total_seniors: seniors.length,
    by_risk_level: {
      LOW: byRisk["LOW"] || 0,
      MODERATE: byRisk["MODERATE"] || 0,
      HIGH: byRisk["HIGH"] || 0,
      URGENT_REVIEW: byRisk["URGENT_REVIEW"] || 0,
    },
    active_alerts_count: activeAlerts,
    acknowledged_alerts_count: ackAlerts,
    resolved_alerts_count: resAlerts,
    escalated_alerts_count: escAlerts,
    overdue_checkins_count: overdueCheckins,
    is_mock_data: true,
  };
}

